        insertComp.run([
          item.id,
          item.name,
          item.website,
          item.careers_url,
          item.city,
          item.country,
          item.description,
          item.industry,
          item.is_gaming,
          JSON.stringify(item.technologies),
          JSON.stringify(item.departments),
          JSON.stringify(item.products),
          item.priority,
          item.fit_score,
          JSON.stringify(item.fit_reasons),
          item.is_speculative
        ]);
        addedCount++;
