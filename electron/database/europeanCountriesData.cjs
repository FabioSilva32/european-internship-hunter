function seedEuropeanCountriesData(dbInstance) {
  if (!dbInstance) return;

  try {
    // 1. Remove Netherlands from active search & selection without breaking any foreign keys
    dbInstance.exec("UPDATE opportunities SET is_active = 0 WHERE country = 'Netherlands' OR country_code = 'NL';");
    dbInstance.exec("DELETE FROM contacts WHERE company_id IN (SELECT id FROM companies WHERE country = 'Netherlands' OR country_code = 'NL');");
    dbInstance.exec("DELETE FROM opportunities WHERE country = 'Netherlands' OR country_code = 'NL';");
    dbInstance.exec("DELETE FROM companies WHERE (country = 'Netherlands' OR country_code = 'NL') AND id NOT IN (SELECT DISTINCT company_id FROM applications WHERE company_id IS NOT NULL);");
    dbInstance.exec("DELETE FROM settings WHERE key = 'ipca_scholarship_nl_eur';");
    dbInstance.exec("UPDATE companies SET country_code = 'PL' WHERE country = 'Poland' AND (country_code IS NULL OR country_code = '');");
    dbInstance.exec("UPDATE opportunities SET country_code = 'PL' WHERE country = 'Poland' AND (country_code IS NULL OR country_code = '');");

    const insertCompany = dbInstance.prepare(`
      INSERT OR REPLACE INTO companies (
        id, name, website, careers_url, city, country, country_code, description, industry, is_gaming,
        technologies, departments, products, priority, fit_score, fit_reasons, is_speculative_candidate
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    const insertContact = dbInstance.prepare(`
      INSERT OR REPLACE INTO contacts (
        id, company_id, name, role, email, source_type, is_verified
      ) VALUES (?, ?, ?, ?, ?, ?, 1)
    `);

    const insertOpportunity = dbInstance.prepare(`
      INSERT OR REPLACE INTO opportunities (
        id, company_id, title, description, city, country, country_code, category, work_arrangement,
        is_official_vacancy, required_technologies, internship_start, internship_end, duration_months,
        application_deadline, salary_info, language_requirements, source_name, source_url, fit_score, is_active
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1)
    `);

    let addedCount = 0;
    for (const item of EUROPEAN_COMPANIES) {
      insertCompany.run(
        item.id,
        item.name,
        item.website,
        item.careers_url,
        item.city,
        item.country,
        item.country_code,
        item.description,
        item.industry,
        item.is_gaming,
        JSON.stringify(item.technologies),
        JSON.stringify(item.departments),
        JSON.stringify(item.products),
        item.priority,
        item.fit_score,
        JSON.stringify(item.fit_reasons),
        item.is_speculative_candidate
      );
      addedCount++;

      if (item.contact) {
        insertContact.run(
          item.contact.id,
          item.id,
          item.contact.name,
          item.contact.role,
          item.contact.email,
          item.contact.source_type
        );
      }

      if (item.opportunity) {
        const opp = item.opportunity;
        insertOpportunity.run(
          opp.id,
          item.id,
          opp.title,
          opp.description,
          item.city,
          item.country,
          item.country_code,
          opp.category,
          opp.work_arrangement,
          opp.is_official_vacancy,
          JSON.stringify(opp.required_technologies),
          opp.internship_start,
          opp.internship_end,
          opp.duration_months,
          opp.application_deadline || '2026-11-30',
          opp.salary_info,
          opp.language_requirements,
          opp.source_name,
          opp.source_url,
          opp.fit_score
        );
      }
    }

    if (typeof dbInstance.save === 'function') {
      dbInstance.save();
    }
    console.log(`[DB] Seeded ${addedCount} verified companies across 10 new European countries (NL removed).`);
  } catch (err) {
    console.error('[DB] Error seeding European countries data:', err);
  }
}

